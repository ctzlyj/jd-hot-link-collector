/** Serialized and executed inside the task page; context never leaves page memory. */
function dispatch(sku,classify,project,validate){
 if(location.hostname!=='item.jd.com')return JSON.stringify({ok:false,reason:location.hostname==='cfe.m.jd.com'?'VERIFICATION_REQUIRED':'TASK_ITEM_PAGE_REQUIRED'});
 if(window.__jdCollectorJob&&window.__jdCollectorJob.phase!=='DONE')return JSON.stringify({ok:false,reason:'REQUEST_IN_FLIGHT'});
 const saved=window.__jdNativeRequestContext;
 if(Array.isArray(saved?.allowedSkuIds)&&!saved.allowedSkuIds.includes(sku))return JSON.stringify({ok:false,reason:'SOURCE_PRODUCT_CONTEXT_MISMATCH'});
 const native=saved?.url||performance.getEntriesByType('resource').map(x=>x.name).reverse().find(x=>{try{const u=new URL(x);return u.hostname==='api.m.jd.com'&&u.searchParams.get('functionId')==='pc_detailpage_wareBusiness'&&u.searchParams.has('h5st')}catch{return false}});
 if(!native)return JSON.stringify({ok:false,reason:'NORMAL_REQUEST_CONTEXT_MISSING'});
 if(typeof window.PSign?.sign!=='function'||typeof window.SHA256!=='function'||typeof window.getJsToken!=='function')return JSON.stringify({ok:false,reason:'PAGE_SDK_MISSING'});
 const job={phase:'TOKEN',sku,started:Date.now(),sent:false};window.__jdCollectorJob=job;
 let xhr=null,finished=false;
 const finish=fields=>{if(finished)return;finished=true;Object.assign(job,fields,{phase:'DONE'})};
 window.__jdCollectorAbort={abort:()=>{if(finished)return;finish({ok:false,reason:'REQUEST_ABORTED'});xhr?.abort()}};
 (async()=>{
  try{
   const u=new URL(native),body=JSON.parse(u.searchParams.get('body'));
   if(u.hostname!=='api.m.jd.com'||u.searchParams.get('functionId')!=='pc_detailpage_wareBusiness')throw Error('NORMAL_REQUEST_CONTEXT_MISSING');
   if(!body.area)throw Error('ADDRESS_CONTEXT_MISSING');body.skuId=sku;
   const rawBody=JSON.stringify(body),t=Date.now();
   const token=await new Promise(resolve=>window.getJsToken(v=>resolve(v?.jsToken||'')));
   if(finished)return;if(!token)throw Error('PAGE_CONTEXT_MISSING');
   job.phase='SIGN';
   const signed=await window.PSign.sign({appid:u.searchParams.get('appid'),clientVersion:u.searchParams.get('clientVersion'),client:u.searchParams.get('client'),t,body:window.SHA256(rawBody),functionId:'pc_detailpage_wareBusiness'});
   if(finished)return;if(!signed?.h5st)throw Error('NORMAL_SIGNATURE_MISSING');
   const values=Object.fromEntries(u.searchParams);values.body=rawBody;values.scval=sku;values.t=String(t);values.h5st=encodeURI(signed.h5st);values['x-api-eid-token']=token;
   const enc=v=>encodeURIComponent(v).replace(/%3A/gi,':').replace(/%24/g,'$').replace(/%2C/gi,',').replace(/%20/g,'+').replace(/%5B/gi,'[').replace(/%5D/gi,']');
   const url=u.origin+u.pathname+'?'+Object.entries(values).map(([k,v])=>enc(k)+'='+enc(v)).join('&');
   const headers={'Accept':'application/json, text/plain, */*','Content-Type':'application/x-www-form-urlencoded'};
   // These values are generated by the page. Never manufacture device context or put it in files.
   const allowed={'x-skuid-param':'X-Skuid-Param','x-sdx':'x-sdx','soarate':'soaRate'};
   for(const [k,v] of Object.entries(saved?.headers||{})){const name=allowed[k.toLowerCase()];if(name&&typeof v==='string')headers[name]=v}
   const pageParams=new URL(location.href).searchParams;
   for(const [key,name] of [['pcdk','X-Skuid-Param'],['sdx','x-sdx'],['soaRate','soaRate']]){const value=pageParams.get(key);if(value)headers[name]=value}
   xhr=new XMLHttpRequest();xhr.open('GET',url,true);xhr.withCredentials=true;xhr.timeout=15000;
   for(const [k,v] of Object.entries(headers))xhr.setRequestHeader(k,v);
   xhr.onload=()=>{
    if(finished)return;const text=xhr.responseText;let raw=null;try{raw=JSON.parse(text)}catch{}
    const outcome=classify(xhr.status,text,raw,xhr.getResponseHeader('retry-after'));
    if(!outcome.ok){finish({...outcome,sent:true,evidence:{httpStatus:xhr.status,responseSku:String(raw?.pageConfigVO?.skuid||''),isOver:raw?.pageConfigVO?.isOver,itemOverTip:raw?.itemOverVO?.itemOverTip}});return}
    const data=project(raw);
    try{validate(sku,data);finish({ok:true,sent:true,data})}
    catch(e){finish({ok:false,sent:true,reason:e.message,...(e.message==='ARRIVAL_PRICE_MISSING'?{partialData:data}:{} )})}
   };
   xhr.onerror=()=>finish({ok:false,sent:true,reason:'NETWORK_ERROR'});
   xhr.ontimeout=()=>finish({ok:false,sent:true,reason:'REQUEST_TIMEOUT'});
   xhr.onabort=()=>finish({ok:false,sent:job.sent,reason:'REQUEST_ABORTED'});
   job.phase='FETCH';job.sent=true;xhr.send(null);
  }catch(e){
   const known=['ADDRESS_CONTEXT_MISSING','PAGE_CONTEXT_MISSING','NORMAL_SIGNATURE_MISSING','NORMAL_REQUEST_CONTEXT_MISSING'];
   finish({ok:false,reason:known.includes(e.message)?e.message:'LOCAL_PAGE_ERROR',errorEvidence:{name:['Error','TypeError','SyntaxError','ReferenceError'].includes(e.name)?e.name:'Error',phase:job.phase}});
  }
 })();
 return JSON.stringify({ok:true,phase:'STARTED',sku});
}

export function collectExpression(sku){
 if(!/^\d{8,}$/.test(String(sku)))throw Error('INVALID_SKU');
 const body=`(async()=>{const started=JSON.parse((${dispatch.toString()})(${JSON.stringify(String(sku))},${classifyResponse.toString()},${project.toString()},${validate.toString()}));if(!started.ok)return JSON.stringify(started);const deadline=Date.now()+20000;while(Date.now()<deadline){await new Promise(r=>setTimeout(r,50));const job=window.__jdCollectorJob;if(job&&job.phase==='DONE')return JSON.stringify(job);}return JSON.stringify({phase:'TIMEOUT'});})()`;
 return body;
}
export function collectBatchExpression(skus){
 const list=skus.map(s=>String(s));
 for(const s of list)if(!/^\d{8,}$/.test(s))throw Error('INVALID_SKU');
 return `(async()=>{const out=[];const skus=${JSON.stringify(list)};const dispatch=${dispatch.toString()};const classify=${classifyResponse.toString()};const project=${project.toString()};const validate=${validate.toString()};for(const sku of skus){const started=JSON.parse(dispatch(sku,classify,project,validate));if(!started.ok){out.push({sku,result:started});continue}const deadline=Date.now()+20000;let job=null;while(Date.now()<deadline){await new Promise(r=>setTimeout(r,25));job=window.__jdCollectorJob;if(job&&job.phase==='DONE')break}out.push({sku,result:job&&job.phase==='DONE'?job:{phase:'TIMEOUT'}})}return JSON.stringify(out)})()`;
}
